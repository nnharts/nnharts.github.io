/* Подвал: живая посещаемость из /api/stats (сервис fundus-stats).
   Цифра слева - за последний месяц нарастающим итогом, не за сутки.
   Токен Метрики держим на сервере, в страницу он не попадает.
   Если сервис недоступен, строка просто не появляется и вёрстка не ломается. */
(function () {
  var MON = ['января','февраля','марта','апреля','мая','июня','июля','августа',
             'сентября','октября','ноября','декабря'];
  var el = document.getElementById('g-visits');
  if (!el) return;
  fetch('https://fundus.hartschenberg.de/api/stats').then(function (r) { return r.ok ? r.json() : null }).then(function (d) {
    if (!d || !d.total) return;
    var day = '';
    if (d.since) {
      var p = d.since.split('-');
      day = parseInt(p[2], 10) + ' ' + MON[parseInt(p[1], 10) - 1] + ' ' + p[0];
    }
    /* Показываем месяц нарастающим итогом, а не сутки: на нашем трафике
       дневная цифра скачет от нуля и читается как «сайт умер». Пока счётчик
       работает меньше месяца, окно шире всей истории и обе цифры совпадают,
       поэтому в этом случае печатаем только «всего». */
    var m = d.month && d.month.users, days = (d.month && d.month.days) || 30;
    var head = (m && m !== d.total.users) ? 'Посетителей: за месяц ' + m + ' · всего '
                                          : 'Посетителей: всего ';
    el.textContent = head + d.total.users + (day ? ' (с ' + day + ')' : '');
    el.title = 'Данные Яндекс.Метрики. «За месяц» — сумма за последние ' + days
             + ' дней, включая сегодня.' + (day ? ' Счётчик установлен ' + day
             + ', более ранние заходы в статистику не попали.' : '');
  }).catch(function () {});
})();
